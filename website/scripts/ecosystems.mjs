// Write the coverage matrix on the ecosystem overview (src/content/docs/docs/ecosystems/index.md)
// from `fleetreach ecosystems --format markdown`, so the page states what the code reads. Only
// the region between the two markers is replaced.
//
//   node scripts/ecosystems.mjs          rewrite the page
//   node scripts/ecosystems.mjs --check  exit 1 if it is out of date (CI)
//
// FLEETREACH names the binary (default: ../target/release/fleetreach).

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const site = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const page = join(site, "src", "content", "docs", "docs", "ecosystems", "index.md");
const binary = process.env.FLEETREACH ?? resolve(site, "..", "target", "release", "fleetreach");
const check = process.argv.includes("--check");
const begin = "<!-- coverage matrix: generated by scripts/ecosystems.mjs -->";
const end = "<!-- end coverage matrix -->";

const matrix = execFileSync(binary, ["ecosystems", "--format", "markdown"], {
  encoding: "utf8",
  env: { PATH: process.env.PATH, NO_COLOR: "1" },
});
const before = readFileSync(page, "utf8");
const start = before.indexOf(begin);
const stop = before.indexOf(end);
if (start < 0 || stop < start) {
  console.error(`${page}: the coverage matrix markers are missing`);
  process.exit(1);
}
const after = before.slice(0, start + begin.length) + "\n\n" + matrix + "\n" + before.slice(stop);
if (after === before) {
  console.error("coverage matrix up to date");
} else if (check) {
  console.error("out of date: ecosystems/index.md; run `npm run ecosystems` in website/ and commit the result");
  process.exit(1);
} else {
  writeFileSync(page, after);
  console.error("coverage matrix written");
}
