#!/usr/bin/env bash
#
# Render the Homebrew formula for a released version from its SHA256SUMS file.
#
#   scripts/render-formula.sh 1.2.0 dist/SHA256SUMS > fleetreach.rb
#
# Used by .github/workflows/release.yml; runnable locally to inspect the output.
set -euo pipefail

VERSION="${1:?usage: $0 <version> <SHA256SUMS>}"
SUMS="${2:?usage: $0 <version> <SHA256SUMS>}"
BASE="https://github.com/tess-fun/fleetreach/releases/download/v${VERSION}"

sha() {
  local file="fleetreach-${VERSION}-$1.tar.gz"
  local sum
  sum="$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$SUMS")"
  [ -n "$sum" ] || { echo "no checksum for $file in $SUMS" >&2; exit 1; }
  echo "$sum"
}

cat <<EOF
# Generated by scripts/render-formula.sh for fleetreach ${VERSION}. Do not edit by hand.
class Fleetreach < Formula
  desc "Fleet-wide dependency security audit across 12 ecosystems"
  homepage "https://tess-fun.github.io/fleetreach/"
  version "${VERSION}"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "${BASE}/fleetreach-${VERSION}-aarch64-apple-darwin.tar.gz"
      sha256 "$(sha aarch64-apple-darwin)"
    end
    on_intel do
      url "${BASE}/fleetreach-${VERSION}-x86_64-apple-darwin.tar.gz"
      sha256 "$(sha x86_64-apple-darwin)"
    end
  end

  on_linux do
    on_arm do
      url "${BASE}/fleetreach-${VERSION}-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$(sha aarch64-unknown-linux-gnu)"
    end
    on_intel do
      url "${BASE}/fleetreach-${VERSION}-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$(sha x86_64-unknown-linux-gnu)"
    end
  end

  # Fleet sources (\`[[source]]\`, \`fleetreach fleet sync\`) clone repos with git.
  depends_on "git" => :recommended

  def install
    bin.install "fleetreach"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/fleetreach --version")
  end
end
EOF
